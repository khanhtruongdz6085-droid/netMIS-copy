    static BigDecimal money(String s){return s==null?null:new BigDecimal(s);}
    static LocalDate day(String s){return s==null?null:LocalDate.parse(s);}
    static LocalDateTime moment(String s){return s==null?null:LocalDateTime.parse(s);}

    public static NetCafe sample() {
        NetCafe c=new NetCafe();
        for(String line:DATA.split("\n")){
            if(line.isBlank())continue;
            String[] a=line.split("\t",-1);
            switch(a[0]){
                        case "SECTION":c.addSection(new ComputerSection(a[1],a[2],money(a[3])));break;
                        case "COMPUTER":c.addComputer(new Computer(a[1],c.getComputerSectionDao().findById(a[2]).orElseThrow(),ComputerStatus.valueOf(a[3])));break;
                        case "CUSTOMER":c.addCustomer(new Customer(a[1],a[2]));break;
                        case "EMPLOYEE":c.addEmployee(new Employee(a[1],a[2],EmployeeStatus.valueOf(a[3])));break;
                        case "FOOD":c.addFood(new Food(a[1],a[2],money(a[3]),Integer.parseInt(a[4])));break;
                        case "OPEN":c.openSession(a[1],c.getCustomerDao().findById(a[2]).orElseThrow(),c.getComputerDao().findById(a[3]).orElseThrow(),c.getEmployeeDao().findById(a[4]).orElseThrow(),moment(a[5]));break;
                        case "ORDER":{
                            String[] entries=a[5].split(",");Food[] foods=new Food[entries.length];int[] quantities=new int[entries.length];
                            for(int i=0;i<entries.length;i++){String[] pair=entries[i].split(":");foods[i]=c.getFoodDao().findById(pair[0]).orElseThrow();quantities[i]=Integer.parseInt(pair[1]);}
                            c.order(a[1],c.getSessionDao().findById(a[2]).orElseThrow(),c.getEmployeeDao().findById(a[3]).orElseThrow(),moment(a[4]),foods,quantities);break;
                        }
                        case "END":c.endSession(c.getSessionDao().findById(a[1]).orElseThrow(),moment(a[2]));break;
                        case "RECEIPT":c.issueReceipt(a[1],c.getSessionDao().findById(a[2]).orElseThrow(),c.getEmployeeDao().findById(a[3]).orElseThrow());break;
                        case "PAY":{
                            Receipt r=c.getReceiptDao().findById(a[2]).orElseThrow();
                            c.pay(a[1],r,moment(a[3]),PaymentMethod.valueOf(a[4]),r.getTotalAmount());break;
                        }
                        case "RESTOCK":c.restockFood(c.getFoodDao().findById(a[1]).orElseThrow(),Integer.parseInt(a[2]));break;

                default:throw new IllegalArgumentException("Unknown event: "+a[0]);
            }
        }
        return c;
    }

